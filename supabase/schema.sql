-- Supabase Schema for Cafe Control Application
-- This schema creates all tables, relationships, and policies needed for the application

-- Enable UUID extension
create extension if not exists "uuid-ossp";

-- Create custom enums
create type order_status as enum ('paid', 'unpaid');
create type streak_goal_types as enum ('none', 'daily', 'week', 'month');

-- Create tables

-- Additional charges table
create table public.additional_charges (
    id integer generated by default as identity primary key,
    amount numeric not null,
    created_at timestamp with time zone default now(),
    is_active boolean default true,
    name text not null,
    icon_name text,
    description text
);

-- Menu categories table
create table public.menu_categories (
    id integer generated by default as identity primary key,
    name text not null unique,
    icon_name text,
    created_at timestamp with time zone default now()
);

-- Menu table
create table public.menu (
    id integer generated by default as identity primary key,
    name text not null,
    description text,
    price numeric not null check (price >= 0),
    category text references menu_categories(name) on delete set null,
    image_url text,
    ingredients jsonb,
    created_at timestamp with time zone default now(),
    updated_at timestamp with time zone default now()
);

-- Orders table
create table public.orders (
    id uuid primary key default uuid_generate_v4(),
    customer_name text,
    customer_contact text,
    is_togo boolean default false,
    items jsonb not null,
    notes text,
    order_name text,
    status order_status default 'unpaid',
    total_price numeric not null check (total_price >= 0),
    created_at timestamp with time zone default now(),
    updated_at timestamp with time zone default now()
);

-- Order items table
create table public.order_items (
    id integer generated by default as identity primary key,
    menu_item_id integer references menu(id) on delete set null,
    order_id uuid references orders(id) on delete cascade,
    price_at_time numeric not null check (price_at_time >= 0),
    quantity integer not null check (quantity > 0),
    created_at timestamp with time zone default now()
);

-- Profiles table for storing user metadata
create table public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text,
    phone text,
    avatar_url text,
    created_at timestamp with time zone default now(),
    updated_at timestamp with time zone default now()
);

-- Create view for menu with totals
create view public.menu_with_totals as
select
    m.id,
    m.name,
    m.description,
    m.price,
    m.category,
    m.image_url,
    m.ingredients,
    m.created_at,
    m.updated_at,
    mc.name as category_name,
    mc.icon_name as category_icon,
    count(oi.id) as total_orders,
    sum(oi.quantity) as total_quantity,
    count(distinct oi.order_id) as unique_orders
from menu m
left join menu_categories mc on m.category = mc.name
left join order_items oi on m.id = oi.menu_item_id
group by m.id, m.name, m.description, m.price, m.category, m.image_url, m.ingredients, m.created_at, m.updated_at, mc.name, mc.icon_name;

-- Enable Row Level Security
alter table public.additional_charges enable row level security;
alter table public.menu_categories enable row level security;
alter table public.menu enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.profiles enable row level security;

-- Create policies for additional_charges
create policy "Additional charges are viewable by everyone"
on public.additional_charges for select
using (true);

create policy "Additional charges are editable by authenticated users"
on public.additional_charges for all
using (auth.role() = 'authenticated')
with check (auth.role() = 'authenticated');

-- Create policies for menu_categories
create policy "Menu categories are viewable by everyone"
on public.menu_categories for select
using (true);

create policy "Menu categories are editable by authenticated users"
on public.menu_categories for all
using (auth.role() = 'authenticated')
with check (auth.role() = 'authenticated');

-- Create policies for menu
create policy "Menu items are viewable by everyone"
on public.menu for select
using (true);

create policy "Menu items are editable by authenticated users"
on public.menu for all
using (auth.role() = 'authenticated')
with check (auth.role() = 'authenticated');

-- Create policies for orders
create policy "Staff can manage orders"
on public.orders for all
using (true)
with check (true);

-- Create policies for order_items
create policy "Staff can manage order items"
on public.order_items for all
using (true)
with check (true);

-- Create policies for profiles
create policy "Users can only view their own profile"
on public.profiles for select
using (auth.uid() = id);

create policy "Users can only update their own profile"
on public.profiles for update
using (auth.uid() = id)
with check (auth.uid() = id);

create policy "Users can insert their own profile"
on public.profiles for insert
with check (auth.uid() = id);


-- Create trigger to create profile when user signs up
create function public.handle_new_user()
returns trigger as $$
begin
    insert into public.profiles (id, full_name, phone, avatar_url)
    values (
        new.id,
        new.raw_user_meta_data->>'full_name',
        new.raw_user_meta_data->>'phone',
        new.raw_user_meta_data->>'picture'
    );
    return new;
end;
$$ language plpgsql security definer;

create trigger on_auth_user_created
after insert on auth.users
for each row
execute procedure public.handle_new_user();

